/** Flip / rotate the rows of a template: any combination of a horizontal flip, a vertical flip and a transpose. */
export function transformRows(rows: string[], flipH: boolean, flipV: boolean, transpose: boolean): string[] {
  let out = rows.slice();
  if (flipH) out = out.map(r => r.split('').reverse().join(''));
  if (flipV) out = out.slice().reverse();
  if (transpose) {
    const w = out[0].length, h = out.length;
    const t: string[] = [];
    for (let x = 0; x < w; x++) { let s = ''; for (let y = 0; y < h; y++) s += out[y][x]; t.push(s); }
    out = t;
  }
  return out;
}

/** A random orientation: flips are free, a transpose (90-degree turn) half the time. */
export function randomOrientation(rows: string[]): string[] {
  return transformRows(rows, oneIn(2), oneIn(2), oneIn(2));
}

/** Glyphs a walker can pass (used when checking a template and when choosing entrances). */
export function vaultGlyphPassable(c: string): boolean { return c !== '%' && c !== '#' && c !== 'X' && c !== '*' && c !== ' '; }

export interface PlacedVault {
  w: number;
  h: number;
  /** Grids just outside the border doors: where tunnels should be aimed. */
  entrances: Pos[];
  rating: number;
}

/**
 * Stamp a vault template with its top-left corner at (x0, y0). `rows` may be a transformed copy of
 * the template's rows. Monsters and objects go through `hooks`.
 */
export function placeVault(lv: Level, tpl: VaultTemplate, x0: number, y0: number, depth: number, hooks: GenHooks, rows: string[] = tpl.rows): PlacedVault {
  const h = rows.length, w = rows[0].length;
  const inner = tpl.kind === 'greater' ? T.PERM : T.GRANITE;
  const entrances: Pos[] = [];
  const lockPower = () => 1 + randint0(Math.min(7, 1 + Math.floor(depth / 5)));
  for (let ry = 0; ry < h; ry++) {
    for (let rx = 0; rx < w; rx++) {
      const c = rows[ry][rx];
      if (c === ' ') continue;
      const x = x0 + rx, y = y0 + ry;
      addFlag(lv, x, y, F.VAULT);
      switch (c) {
        case '%': setTile(lv, x, y, T.GRANITE); continue;
        case '#': setTile(lv, x, y, inner); continue;
        case 'X': setTile(lv, x, y, T.PERM); continue;
        case '*': setTile(lv, x, y, T.MAGMA_K); continue;
      }
      // Everything else is walkable and part of the vault's room.
      addFlag(lv, x, y, F.ROOM);
      setTile(lv, x, y, T.FLOOR);
      switch (c) {
        case '+':
          setTile(lv, x, y, T.DOOR_CLOSED);
          if (oneIn(2)) setAux(lv, x, y, lockPower());
          if (rx === 0) entrances.push({ x: x - 1, y });
          else if (rx === w - 1) entrances.push({ x: x + 1, y });
          else if (ry === 0) entrances.push({ x, y: y - 1 });
          else if (ry === h - 1) entrances.push({ x, y: y + 1 });
          break;
        case "'": setTile(lv, x, y, T.DOOR_OPEN); break;
        case '^': setTile(lv, x, y, T.TRAP_HIDDEN); setAux(lv, x, y, pickTrap(depth)); break;
        case '&': hooks.placeMonster(lv, depth + 5, x, y, true, false); break;
        case '@': hooks.placeMonster(lv, depth + 11, x, y, true, false); break;
        case '9': hooks.placeMonster(lv, depth + 9, x, y, true, false); hooks.placeObject(lv, depth + 7, x, y, true, false); break;
        case '8': hooks.placeMonster(lv, depth + 9, x, y, true, false); hooks.placeObject(lv, depth + 7, x, y, true, true); break;
        case '$': hooks.placeGold(lv, depth, x, y); break;
        case ',': {
          // Angband's ',': half the time a monster, half the time an object, and sometimes a trap.
          const mon = oneIn(2), obj = oneIn(2);
          if (mon) hooks.placeMonster(lv, depth + 3, x, y, true, false);
          if (obj) hooks.placeObject(lv, depth + 7, x, y, false, false);
          else if (!mon && oneIn(2)) { setTile(lv, x, y, T.TRAP_HIDDEN); setAux(lv, x, y, pickTrap(depth)); }
          break;
        }
      }
    }
  }
  return { w, h, entrances, rating: tpl.rating + (randint1(3) - 2) };
}
