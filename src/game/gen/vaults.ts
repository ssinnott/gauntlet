// Hand-drawn vaults in the language of Angband's vault.txt, and the stamper that turns one into
// tiles. The dungeon generator picks a template that suits the depth, flips or rotates it, claims
// the blocks it needs and calls `placeVault`; monsters and objects go through the `GenHooks` it is
// handed (the generator passes deferred hooks so the contents arrive with everything else).
//
// Glyph legend (one character per grid):
//   %   outer wall: granite, so tunnels can pierce it and the vault is never sealed off
//   #   inner wall: granite in a lesser vault, permanent rock in a greater vault
//   X   permanent rock, always
//   *   mineral vein with treasure
//   .   floor
//   +   closed door (sometimes locked)
//   '   open door
//   ^   hidden trap
//   &   monster (depth + 5)
//   @   monster (depth + 11)
//   9   monster (depth + 9) on a good object
//   8   monster (depth + 9) on a great object
//   $   gold
//   ,   random: perhaps a monster, perhaps an object, perhaps a trap
//       (space) left untouched
// Every floor grid inside a vault is flagged VAULT | ROOM and is never lit. The border of a
// template must be all '%' apart from doors, and everything inside must be reachable from a border
// door (walking through closed doors), because the simulator checks that levels stay connected.
import { type Level, type Pos, T, F, TRAP_KINDS } from '../types.ts';
import { setTile, addFlag, setAux } from '../level.ts';
import { randint0, randint1, oneIn } from '../util.ts';
import type { GenHooks } from './dungeon.ts';

export interface VaultTemplate {
  name: string;
  kind: 'lesser' | 'greater';
  /** Shallowest depth the vault can appear at. */
  depth: number;
  /** Higher is rarer: a template is picked with weight 1 / rarity. */
  rarity: number;
  /** Danger / loot rating, for level feelings. */
  rating: number;
  rows: string[];
}

/** Pick a trap kind suited to the depth (trap doors and pits are common everywhere; nastier runes turn up deeper). */
export function pickTrap(depth: number): number {
  const n = TRAP_KINDS.length;
  for (let i = 0; i < 20; i++) {
    const k = randint0(n);
    if (k >= 6 && depth < 5) continue;
    if (k >= 11 && depth < 15) continue;
    return k;
  }
  return 1;
}

