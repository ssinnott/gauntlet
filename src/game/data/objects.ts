// Object kinds, ego-items and artifacts, modelled on Angband 3.0's object list. Pure data: every
// consumable and device carries an `effect` that effects.ts executes. Conventions:
//   - lights: `pval` = radius, `recharge` = starting fuel in turns (absent on NO_FUEL lights)
//   - food: `pval` = nutrition
//   - diggers: TUNNEL flag with `pval` = digging bonus; launchers: `multiplier` + `ammo`
//   - chests: `pval` = chest level (lock and trap difficulty); gold: `cost` = base value per pile
//   - flavoured kinds (rings, amulets, potions, scrolls, wands, staffs, rods) get a neutral colour;
//     the run-time flavour supplies the real one
//   - wearables with an ACTIVATE flag use `effect` as the activation and `recharge` as its cooldown
import type { ObjectKind, EgoKind, ArtifactKind, Effect, TVal, Timed, Element, Stat, DetectWhat } from '../types.ts';

// ---------------------------------------------------------------------------------------------
// Helpers (data only; these keep each kind on one line)

const NEUTRAL = '#c8c8c8', STEEL = '#b0b8c0', IRON = '#7c848c', WOOD = '#8b5a2b', LEATHER = '#a0714f', CHAIN = '#9aa3ad', GOLD = '#f4d03f', MITHRIL = '#a8c8d8';
const IGNORE_ALL = ['IGNORE_ACID', 'IGNORE_ELEC', 'IGNORE_FIRE', 'IGNORE_COLD'] as const;
const ALL_CURES: Timed[] = ['blind', 'confused', 'poisoned', 'stun', 'cut', 'image', 'afraid'];

type X = Partial<ObjectKind>;
const kind = (id: string, name: string, tval: TVal, color: string, level: number, rarity: number, cost: number, weight: number, x: X = {}): ObjectKind =>
  ({ id, name, tval, color, level, rarity, cost, weight, ...x });
const weapon = (tval: 'sword' | 'hafted' | 'polearm' | 'digger', id: string, name: string, level: number, rarity: number, cost: number, weight: number, dice: [number, number], x: X = {}) =>
  kind(id, name, tval, STEEL, level, rarity, cost, weight, { dice, toHit: 0, toDam: 0, ...x });
const armor = (tval: TVal, color: string, id: string, name: string, level: number, rarity: number, cost: number, weight: number, ac: number, x: X = {}) =>
  kind(id, name, tval, color, level, rarity, cost, weight, { ac, toAc: 0, ...x });
const ammo = (tval: 'shot' | 'arrow' | 'bolt', id: string, name: string, level: number, rarity: number, cost: number, weight: number, dice: [number, number], x: X = {}) =>
  kind(id, name, tval, STEEL, level, rarity, cost, weight, { dice, toHit: 0, toDam: 0, stackable: true, ...x });
const potion = (id: string, name: string, level: number, rarity: number, cost: number, effect: Effect, x: X = {}) =>
  kind('potion_' + id, 'Potion of ' + name, 'potion', NEUTRAL, level, rarity, cost, 4, { flavored: true, stackable: true, effect, ...x });
const scroll = (id: string, name: string, level: number, rarity: number, cost: number, effect: Effect, x: X = {}) =>
  kind('scroll_' + id, 'Scroll of ' + name, 'scroll', NEUTRAL, level, rarity, cost, 5, { flavored: true, stackable: true, effect, ...x });
const wand = (id: string, name: string, level: number, rarity: number, cost: number, charges: [number, number], effect: Effect, x: X = {}) =>
  kind('wand_' + id, 'Wand of ' + name, 'wand', NEUTRAL, level, rarity, cost, 10, { flavored: true, charges, effect, ...x });
const staff = (id: string, name: string, level: number, rarity: number, cost: number, charges: [number, number], effect: Effect, x: X = {}) =>
  kind('staff_' + id, 'Staff of ' + name, 'staff', NEUTRAL, level, rarity, cost, 50, { flavored: true, charges, effect, ...x });
const rod = (id: string, name: string, level: number, rarity: number, cost: number, recharge: number, effect: Effect, x: X = {}) =>
  kind('rod_' + id, 'Rod of ' + name, 'rod', NEUTRAL, level, rarity, cost, 15, { flavored: true, recharge, effect, ...x });
const ring = (id: string, name: string, level: number, rarity: number, cost: number, x: X = {}) =>
  kind('ring_' + id, 'Ring of ' + name, 'ring', NEUTRAL, level, rarity, cost, 2, { flavored: true, ...x });
const amulet = (id: string, name: string, level: number, rarity: number, cost: number, x: X = {}) =>
  kind('amulet_' + id, 'Amulet of ' + name, 'amulet', NEUTRAL, level, rarity, cost, 3, { flavored: true, ...x });
const food = (id: string, name: string, level: number, rarity: number, cost: number, weight: number, pval: number, x: X = {}) =>
  kind(id, name, 'food', '#d2a86a', level, rarity, cost, weight, { pval, stackable: true, ...x });
const mushroom = (id: string, name: string, level: number, rarity: number, cost: number, effect: Effect, x: X = {}) =>
  kind('mushroom_' + id, 'Mushroom of ' + name, 'food', '#c8a2c8', level, rarity, cost, 1, { pval: 500, stackable: true, effect, ...x });

const seq = (...effects: Effect[]): Effect => ({ kind: 'seq', effects });
const timed = (effect: Timed, base: number, dice?: [number, number]): Effect => ({ kind: 'timed', effect, base, dice });
const heal = (amount: number, cure?: Timed[], percent?: number): Effect => ({ kind: 'heal', amount, percent, cure });
const cure = (...c: Timed[]): Effect => ({ kind: 'cure', cure: c });
const bolt = (element: Element, dice: [number, number], beam?: number): Effect => ({ kind: 'bolt', element, dice, beam });
const ball = (element: Element, dam: number, radius = 2): Effect => ({ kind: 'ball', element, dam, radius });
const breath = (element: Element, dam: number): Effect => ({ kind: 'breath', element, dam });
const detect = (...what: DetectWhat[]): Effect => ({ kind: 'detect', what });
const restore = (stat: Stat | 'all'): Effect => ({ kind: 'restore_stat', stat });
const gain = (stat: Stat | 'random'): Effect => ({ kind: 'gain_stat', stat });
const lose = (stat: Stat): Effect => ({ kind: 'lose_stat', stat });
const nourish = (amount: number): Effect => ({ kind: 'nourish', amount });
const dragon = (id: string, name: string, level: number, rarity: number, cost: number, element: Element, dam: number, res: ObjectKind['flags'], color: string, ac = 30) =>
  armor('dragon_armor', color, 'dsm_' + id, name + ' Dragon Scale Mail', level, rarity, cost, 200, ac,
    { toHit: -2, flags: [...(res ?? []), 'ACTIVATE', ...IGNORE_ALL], effect: breath(element, dam), recharge: 450, desc: `Breathes ${element} for ${dam} damage when activated.` });

